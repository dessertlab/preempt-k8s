#!/usr/bin/env python3

"""
Run on the node.
Extracts from the kubelet journal the logs of a stress-bands.sh run and analyzes
queue waiting times, creation slot usage and dequeue order per criticality band.
Requires logging.verbosity >= 4 in the kubelet configuration.

Output files in ./kubelet-patch-analysis/<run-id>:
  kubelet.log   - raw journal of the analysis window
  pods.csv      - one row per pod with its timestamps and durations
  timeline.csv  - used and waiting slots per band over time
  summary.txt   - limits check, per band statistics and order check
"""


import argparse
import csv
import os
import re
import statistics
import subprocess
from datetime import datetime


# Default values and working variables
N = 8
GUARANTEED = "4,2,2"
THRESHOLDS = "10,30"
MIN_LEVEL = 80
STEALING = "true"
RESULTS_ROOT = "./kubelet-patch-analysis"

BANDS = ["high", "medium", "low"]


# Journal line (short-iso-precise) carrying a klog structured message
LINE = re.compile(r'^(\d{4}-\d{2}-\d{2})T\S+ \S+ \S+: [IWEF]\d{4} (\d{2}:\d{2}:\d{2}\.\d{6})\s+\d+ \S+\] "([^"]*)"(.*)$')
# key=value pairs: quoted string, [list] or bare token
KV = re.compile(r'(\w+)=("(?:[^"\\]|\\.)*"|\[[^\]]*\]|\S+)')
# Test pod names generated by stress-bands.sh
NAME = re.compile(r'^band-pod-\d+-l(\d+|none)$')


# Parse command line flags
def parse_args():
    parser = argparse.ArgumentParser(description="Analyze the kubelet logs of a criticality bands stress test.")
    parser.add_argument("-r", dest="run_id", required=True, help="run ID printed by stress-bands.sh, used to name the results directory")
    parser.add_argument("-s", dest="since", required=True, help="start of the analysis window, 'YYYY-MM-DD HH:MM:SS'")
    parser.add_argument("-u", dest="until", required=True, help="end of the analysis window, 'YYYY-MM-DD HH:MM:SS'")
    parser.add_argument("-n", dest="n", type=int, default=N, help=f"maxConcurrentPodCreations (default: {N})")
    parser.add_argument("-g", dest="guaranteed", default=GUARANTEED, help=f"guaranteed slots high,medium,low (default: {GUARANTEED})")
    parser.add_argument("-b", dest="thresholds", default=THRESHOLDS, help=f"highBandMinLevel,mediumBandMinLevel (default: {THRESHOLDS})")
    parser.add_argument("-l", dest="min_level", type=int, default=MIN_LEVEL, help=f"criticality.minLevel (default: {MIN_LEVEL})")
    parser.add_argument("-t", dest="stealing", default=STEALING, choices=["true", "false"], help=f"stealing enabled (default: {STEALING})")
    return parser.parse_args()


# Log extraction
def extract_journal(since, until, path):
    cmd = ["journalctl", "-u", "kubelet", "-o", "short-iso-precise", "--no-pager", "--since", since, "--until", until]
    with open(path, "w") as f:
        subprocess.run(cmd, stdout=f, check=True)


# Parsing helpers
def kvs(rest):
    out = {}
    for k, v in KV.findall(rest):
        out[k] = v[1:-1] if v.startswith('"') else v
    return out


def int_list(value):
    return [int(x) for x in value.strip("[]").split(",")]


def short_name(full):
    return full.split("/", 1)[-1]


def ms(a, b):
    return round((b - a).total_seconds() * 1000, 3) if a and b else None


# Analysis
class Analysis:
    def __init__(self, args):
        self.n = args.n
        self.g = [int(x) for x in args.guaranteed.split(",")]
        self.high_max, self.medium_max = (int(x) for x in args.thresholds.split(","))
        self.min_level = args.min_level
        self.stealing = args.stealing == "true"
        self.pods = {}
        self.uid2name = {}
        self.timeline = []
        self.patch_mode = False

    def band_of(self, level):
        if level is None:
            return "low"
        if level <= self.high_max:
            return "high"
        if level <= self.medium_max:
            return "medium"
        return "low"

    def pod(self, name):
        if name not in self.pods:
            m = NAME.match(name)
            level = None if m.group(1) == "none" else int(m.group(1))
            self.pods[name] = {"name": name, "level": level, "band": self.band_of(level)}
        return self.pods[name]

    def mark(self, name, key, t, uid=None):
        if not NAME.match(name):
            return
        if uid:
            self.uid2name[uid] = name
        self.pod(name).setdefault(key, t)

    def parse(self, path):
        with open(path) as f:
            for line in f:
                m = LINE.match(line)
                if not m:
                    continue
                t = datetime.strptime(f"{m.group(1)} {m.group(2)}", "%Y-%m-%d %H:%M:%S.%f")
                msg, kv = m.group(3), kvs(m.group(4))

                if msg == "SyncLoop ADD":
                    for full in re.findall(r'"([^"]+)"', kv.get("pods", "")):
                        self.mark(short_name(full), "arrival", t)
                elif msg == "Pod assigned to criticality band":
                    name = short_name(kv.get("pod", ""))
                    if NAME.match(name):
                        self.patch_mode = True
                    self.mark(name, "enqueued", t, kv.get("podUID"))
                elif msg == "Topology Admit Handler":
                    self.mark(kv.get("podName", ""), "admitted", t, kv.get("podUID"))
                elif msg == "SyncPod enter":
                    self.mark(short_name(kv.get("pod", "")), "sync_enter", t, kv.get("podUID"))
                elif msg == "SyncPod exit":
                    self.mark(short_name(kv.get("pod", "")), "sync_exit", t, kv.get("podUID"))
                elif msg == "SyncLoop (podDoneCh): pod creation done":
                    name = self.uid2name.get(kv.get("podUID"))
                    if name:
                        self.mark(name, "released", t)

                if msg.startswith("SyncLoop (ADD)") or msg.startswith("SyncLoop (podDoneCh)"):
                    if "used" in kv and "waiting" in kv:
                        self.timeline.append([t.isoformat(), msg] + int_list(kv["used"]) + int_list(kv["waiting"]) + [kv.get("inCreation", "")])

    def compute(self):
        rows = sorted(self.pods.values(), key=lambda p: p.get("arrival") or datetime.max)
        for p in rows:
            p["slot_start"] = p.get("admitted") if self.patch_mode else p.get("sync_enter")
            p["slot_end"] = p.get("released") if self.patch_mode else p.get("sync_exit")
            p["wait_ms"] = ms(p.get("arrival"), p.get("admitted"))
            p["slot_ms"] = ms(p["slot_start"], p["slot_end"])
            p["total_ms"] = ms(p.get("arrival"), p.get("sync_exit"))
        return rows

    def limits(self):
        if not self.stealing:
            return dict(zip(BANDS, self.g))
        return {"high": self.n, "medium": self.n - self.g[0], "low": self.g[2]}

    def check_slots(self, rows):
        events = []
        for p in rows:
            if p["slot_start"] and p["slot_end"]:
                events.append((p["slot_start"], 1, p["band"]))
                events.append((p["slot_end"], -1, p["band"]))
        events.sort(key=lambda e: (e[0], e[1]))

        limit = self.limits()
        cur = {b: 0 for b in BANDS}
        peak = {b: 0 for b in BANDS}
        peak_total = 0
        violations = []
        for t, d, b in events:
            cur[b] += d
            total = sum(cur.values())
            peak[b] = max(peak[b], cur[b])
            peak_total = max(peak_total, total)
            if self.patch_mode and d > 0:
                if total > self.n:
                    violations.append(f"{t.time()} total {total} > {self.n}")
                if cur[b] > limit[b]:
                    violations.append(f"{t.time()} {b} {cur[b]} > {limit[b]}")
        return peak_total, peak, violations

    def check_order(self, rows):
        def key(p):
            return (p["level"] if p["level"] is not None else self.min_level + 1, p["arrival"])

        timed = [p for p in rows if p.get("arrival") and p.get("admitted")]
        order_violations = []
        cross = 0
        for a in timed:
            higher_waiting = False
            for b in timed:
                if a is b or b["arrival"] > a["admitted"] or b["admitted"] <= a["admitted"]:
                    continue
                if a["band"] == b["band"] and key(b) < key(a):
                    order_violations.append(f"{a['name']} dequeued before {b['name']}")
                if BANDS.index(b["band"]) < BANDS.index(a["band"]):
                    higher_waiting = True
            cross += higher_waiting
        return order_violations, cross


# Output files
def write_pods(path, rows):
    cols = ["name", "band", "level", "arrival", "admitted", "sync_enter", "sync_exit", "released", "wait_ms", "slot_ms", "total_ms"]
    with open(path, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(cols)
        for p in rows:
            w.writerow([p.get(c).isoformat() if isinstance(p.get(c), datetime) else p.get(c) for c in cols])


def write_timeline(path, timeline):
    with open(path, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["time", "event", "used_high", "used_medium", "used_low", "waiting_high", "waiting_medium", "waiting_low", "inCreation"])
        w.writerows(timeline)


def summary(run_id, a, rows):
    out = [f"Run {run_id}: {len(rows)} pods, mode: {'patch (bands enabled)' if a.patch_mode else 'vanilla'}"]
    missing = [p["name"] for p in rows if not (p.get("arrival") and p["slot_start"] and p["slot_end"])]
    if missing:
        out.append(f"WARNING: {len(missing)} pods with missing timestamps (verbosity < 4 or window too short): {missing[:5]}")

    peak_total, peak, violations = a.check_slots(rows)
    if a.patch_mode:
        limit = a.limits()
        out.append("")
        out.append(f"Peak used slots: total {peak_total} (N={a.n}), " + ", ".join(f"{b} {peak[b]}" for b in BANDS))
        out.append(f"Expected limits ({'with' if a.stealing else 'without'} stealing): total {a.n}, " + ", ".join(f"{b} {limit[b]}" for b in BANDS))
        out.append(f"Limit violations: {len(violations)}" + (f" -> {violations[:5]}" if violations else ""))

    out.append("")
    out.append(f"{'band':<8}{'pods':>6}{'avg wait':>14}{'max wait':>14}{'avg creation':>14}{'arrival->1st sync end':>24}")
    for b in BANDS:
        ps = [p for p in rows if p["band"] == b]

        def stat(key, fn):
            vals = [p[key] for p in ps if p[key] is not None]
            return f"{fn(vals):.1f} ms" if vals else "-"

        out.append(f"{b:<8}{len(ps):>6}{stat('wait_ms', statistics.mean):>14}{stat('wait_ms', max):>14}{stat('slot_ms', statistics.mean):>14}{stat('total_ms', statistics.mean):>24}")

    if a.patch_mode:
        order_violations, cross = a.check_order(rows)
        out.append("")
        out.append(f"Order inversions within a band: {len(order_violations)}" + (f" -> {order_violations[:5]}" if order_violations else ""))
        out.append(f"Pods dequeued while a more critical pod was waiting: {cross} (allowed by the guaranteed shares)")
    return "\n".join(out)


def main():
    args = parse_args()

    # Create results directory
    outdir = os.path.join(RESULTS_ROOT, args.run_id)
    print("Creating results directory...")
    os.makedirs(outdir, exist_ok=True)
    print(f"Results will be stored in: {outdir}")
    print("")

    # Retrieve Kubelet logs
    log_path = os.path.join(outdir, "kubelet.log")
    print(f"Extracting Kubelet journal from '{args.since}' to '{args.until}'...")
    extract_journal(args.since, args.until, log_path)
    print("")

    # Analysis
    print("Starting the analysis...")
    a = Analysis(args)
    a.parse(log_path)
    rows = a.compute()
    print("")

    # Generate output files
    write_pods(os.path.join(outdir, "pods.csv"), rows)
    write_timeline(os.path.join(outdir, "timeline.csv"), a.timeline)
    text = summary(args.run_id, a, rows)
    with open(os.path.join(outdir, "summary.txt"), "w") as f:
        f.write(text + "\n")
    print(text)
    print("")
    print(f"Files in {outdir}: kubelet.log, pods.csv, timeline.csv, summary.txt")
    
    print("Analysis Completed!")


if __name__ == "__main__":
    main()
